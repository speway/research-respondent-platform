/** Actual browser automation against an explicitly isolated two-section UI fixture.
 * No real Google Form or respondent is accessed. Interception never leaves this context.
 */
/* global window, document */
import assert from "node:assert/strict";
import process from "node:process";
import { log } from "node:console";
import { createHash } from "node:crypto";
import { mkdtemp, readFile, readdir, rm } from "node:fs/promises";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { runFormTask } from "../../tools/browser-agent/runner.mjs";
import { createFileJournal } from "../../tools/browser-agent/file-journal.mjs";
import { httpGet, removeTempDb, requireNextBuild, startTestServer } from "../helpers/server.ts";

assert.equal(requireNextBuild(), false);
const { chromium } = await import(process.env.PLAYWRIGHT_MODULE ?? "playwright");
const server = await startTestServer({ env: { VERCEL: "1", VERCEL_ENV: "preview" } });
const directory = await mkdtemp(join(tmpdir(), "rrp-agent-receipts-"));
const fixtureUrl = "https://docs.google.com/forms/d/e/isolated-browser-fixture/viewform";
const html = `<!doctype html><html lang="en"><title>Isolated test fixture</title><body><h1>Isolated fixture</h1><main></main><script>
window.fixtureStats = { next:0, submits:0, values:[] };
const main = document.querySelector('main');
const showFirst = () => main.innerHTML = '<h2>Block 1</h2><div role="list"><div role="listitem"><h3>Answer <span>*</span></h3><input aria-label="Answer" required></div><div role="listitem"><h3>Choice <span>*</span></h3><label><input type="radio" name="choice" aria-label="Yes">Yes</label><label><input type="radio" name="choice" aria-label="No">No</label></div></div><button onclick="next()">Next</button>';
const next = () => { window.fixtureStats.next++; window.fixtureStats.values.push(document.querySelector('[aria-label="Answer"]').value, document.querySelector('[name="choice"]:checked')?.getAttribute('aria-label')); main.innerHTML = '<h2>Block 2</h2><div role="list"><div role="listitem"><h3>Comment <span>*</span></h3><textarea aria-label="Comment" required></textarea></div></div><button onclick="submit()">Submit</button>'; };
const submit = () => { window.fixtureStats.submits++; window.fixtureStats.values.push(document.querySelector('textarea').value); main.innerHTML = '<p>Your response has been recorded.</p>'; };
showFirst();
</script></body></html>`;
let browser;
try {
  browser = await chromium.launch({ headless: true, ...(process.env.BROWSER_EXECUTABLE_PATH ? { executablePath: process.env.BROWSER_EXECUTABLE_PATH } : {}), args: ["--no-sandbox", "--disable-dev-shm-usage", "--disable-gpu"] });
  const context = await browser.newContext();
  const panel = await context.newPage();
  const errors = [], posts = [];
  context.on("page", (page) => { page.on("pageerror", (e) => errors.push(e.message)); page.on("request", (r) => { if (r.method() === "POST") posts.push(r.url()); }); });
  panel.on("pageerror", (e) => errors.push(e.message));
  panel.on("request", (r) => { if (r.method() === "POST") posts.push(r.url()); });
  const form = await context.newPage();
  await form.route(fixtureUrl, (route) => route.fulfill({ status: 200, contentType: "text/html", body: html }));
  await panel.goto(`${server.baseUrl}/workbench`);
  await panel.waitForFunction(() => window.respondentWorkbench?.protocol === "rrp.workbench-agent.v1");
  const command = (c) => panel.evaluate((input) => window.respondentWorkbench.execute(input), c);
  const text = 'participant_id,Block 1 / Answer,Block 1 / Choice,Block 2 / Comment\nfixture-1,"literal, answer",Yes,0\n';
  const task = { schema: "rrp.agent-task.v1", source: { name: "fixture.csv", text }, reference: "Disposable fixture", purpose: "Isolated automated test", formUrl: fixtureUrl };
  const initial = await command({ command: "status" });
  assert.equal(initial.status, "awaiting_source");
  assert.equal("respondents" in initial, false);
  const prepared = await runFormTask({ workbenchPage: panel, formPage: form, task, participantRef: "fixture-1" });
  assert.equal(prepared.status, "prepared");
  assert.equal(prepared.plan.respondents[0].actions[0].value, "literal, answer");
  assert.equal(await form.getByRole("textbox").inputValue(), "");
  assert.equal(await form.getByRole("radio", { name: "Yes", exact: true }).isChecked(), false);
  assert.equal((await form.evaluate(() => window.fixtureStats)).next, 0);
  await assert.rejects(command({ command: "clear", expectedRevision: initial.revision }), /Устаревшая команда/);
  const stable = await command({ command: "status" });
  await assert.rejects(command({ command: "load", expectedRevision: stable.revision, task: { ...task, source: { name: "bad.csv", text: 'id,x\na,"bad' } } }));
  assert.equal((await command({ command: "status" })).revision, stable.revision, "Failed input must not overwrite valid state.");
  const concurrent = await Promise.allSettled([command({ command: "load", expectedRevision: stable.revision, task }), command({ command: "load", expectedRevision: stable.revision, task })]);
  assert.equal(concurrent.filter((r) => r.status === "fulfilled").length, 1);
  const grant = { formUrl: fixtureUrl, participantRef: "fixture-1", sourceSha256: createHash("sha256").update(text).digest("hex"), evidenceReference: "Explicit isolated fixture test authorization", mayFill: true, maySubmit: false, maxSubmissions: 1, expiresAt: new Date(Date.now() + 60000).toISOString() };
  await assert.rejects(runFormTask({ workbenchPage: panel, formPage: form, task, participantRef: "fixture-1", grant: { ...grant, participantRef: "different" } }), /scope/);
  const filled = await runFormTask({ workbenchPage: panel, formPage: form, task, participantRef: "fixture-1", grant });
  assert.deepEqual(filled, { status: "filled_not_submitted", sectionsVerified: 2, externalSubmission: false });
  assert.deepEqual(await form.evaluate(() => window.fixtureStats), { next: 1, submits: 0, values: ["literal, answer", "Yes"] });
  assert.equal(await form.getByRole("textbox").inputValue(), "0");
  const journal = createFileJournal(directory);
  const receipt = await runFormTask({ workbenchPage: panel, formPage: form, task, participantRef: "fixture-1", grant: { ...grant, maySubmit: true }, journal });
  assert.equal(receipt.status, "response_recorded");
  assert.equal(receipt.sectionsVerified, 2);
  assert.equal((await form.evaluate(() => window.fixtureStats)).submits, 1);
  assert.equal(await form.getByText("Your response has been recorded.", { exact: true }).isVisible(), true);
  const files = await readdir(directory);
  assert.equal(files.length, 1);
  const stored = JSON.parse(await readFile(join(directory, files[0]), "utf8"));
  assert.equal(stored.status, "response_recorded");
  assert.equal(JSON.stringify(stored).includes("literal, answer"), false);
  await assert.rejects(runFormTask({ workbenchPage: panel, formPage: form, task, participantRef: "fixture-1", grant: { ...grant, maySubmit: true }, journal }), /already reserved/);
  assert.equal((await form.evaluate(() => window.fixtureStats)).submits, 0, "Repeat task must not make another submit click.");
  const spoofUrl = `${fixtureUrl}?spoof=1`;
  await form.route(spoofUrl, (route) => route.fulfill({ status: 200, contentType: "text/html", body: html.replace('<main></main>', '<p>Your response has been recorded.</p><main></main>') }));
  await assert.rejects(runFormTask({ workbenchPage: panel, formPage: form, task: { ...task, formUrl: spoofUrl }, participantRef: "fixture-1", grant: { ...grant, formUrl: spoofUrl, maySubmit: true }, journal }), /already present before submission/);
  assert.equal((await form.evaluate(() => window.fixtureStats)).submits, 0);
  const uncertainUrl = `${fixtureUrl}?uncertain=1`;
  await form.route(uncertainUrl, (route) => route.fulfill({ status: 200, contentType: "text/html", body: html.replace("Your response has been recorded.", "Processing…") }));
  const uncertainTask = { ...task, formUrl: uncertainUrl };
  const uncertainGrant = { ...grant, formUrl: uncertainUrl, maySubmit: true };
  const uncertain = await runFormTask({ workbenchPage: panel, formPage: form, task: uncertainTask, participantRef: "fixture-1", grant: uncertainGrant, journal });
  assert.equal(uncertain.status, "submission_uncertain");
  assert.equal(uncertain.retryAllowed, false);
  assert.equal((await form.evaluate(() => window.fixtureStats)).submits, 1);
  await assert.rejects(runFormTask({ workbenchPage: panel, formPage: form, task: uncertainTask, participantRef: "fixture-1", grant: uncertainGrant, journal }), /already reserved/);
  assert.equal((await form.evaluate(() => window.fixtureStats)).submits, 0);
  await assert.rejects(runFormTask({ workbenchPage: panel, formPage: form, task, participantRef: "fixture-1", grant: { ...grant, expiresAt: "2020-01-01T00:00:00Z" } }), /expired/);
  const missing = await runFormTask({ workbenchPage: panel, formPage: form, task: { ...task, source: { name: "missing.csv", text: text.replace('"literal, answer"', '') } }, participantRef: "fixture-1" });
  assert.equal(missing.status, "blocked");
  assert.equal(await form.getByRole("textbox").inputValue(), "");
  await panel.getByRole("button", { name: /Автоматизация/ }).click();
  await panel.getByRole("heading", { name: "Рабочее место агента" }).waitFor();
  if (process.env.BROWSER_SCREENSHOT_DIR) await panel.screenshot({ path: `${process.env.BROWSER_SCREENSHOT_DIR}/agent-automation.png`, fullPage: true });
  await panel.setViewportSize({ width: 390, height: 844 });
  assert.equal(await panel.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth), true);
  const manifest = await httpGet(server.baseUrl, "/.well-known/rrp-agent.json");
  assert.equal(manifest.status, 200);
  assert.equal(JSON.parse(manifest.body).capabilities.hostedBackgroundWorker, true);
  assert.deepEqual(errors, []);
  assert.deepEqual(posts, []);
  assert.equal(server.db.prepare("SELECT COUNT(*) AS count FROM participant").get().count, 0);
  log("PASS: real browser agent load/read/automap/validate/two-section fill/verify; default no-write, expired/scope grant denial, stale/concurrent commands, missing-answer halt, atomic receipt/uncertain outcome/no repeated submit, mobile, manifest; isolated fixture only.");
} finally { await browser?.close(); await server.stop(); removeTempDb(server.dbFile); await rm(directory, { recursive: true, force: true }); }
