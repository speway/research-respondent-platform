/** Optional real-browser check. See docs/BROWSER_WORKBENCH.md for runtime prerequisites. */
/* global document, window */
import assert from "node:assert/strict";
import process from "node:process";
import { Buffer } from "node:buffer";
import { log } from "node:console";
import { createHash } from "node:crypto";
import { readFile } from "node:fs/promises";
import { httpGet, removeTempDb, requireNextBuild, startTestServer } from "../helpers/server.ts";

assert.equal(requireNextBuild(), false, "Build the application before browser verification.");
const { chromium } = await import(process.env.PLAYWRIGHT_MODULE ?? "playwright");
const server = await startTestServer({ env: { VERCEL: "1", VERCEL_ENV: "preview" } });
let browser;
try {
  browser = await chromium.launch({ headless: true, ...(process.env.BROWSER_EXECUTABLE_PATH ? { executablePath: process.env.BROWSER_EXECUTABLE_PATH } : {}), args: ["--no-sandbox", "--disable-dev-shm-usage", "--disable-gpu"] });
  const page = await browser.newPage({ viewport: { width: 1440, height: 1050 } });
  const errors = [], posts = [];
  page.on("pageerror", (error) => errors.push(error.message));
  page.on("request", (request) => { if (request.method() === "POST") posts.push(request.url()); });
  await page.goto(`${server.baseUrl}/workbench`);
  await page.getByRole("heading", { name: "База ответов", exact: true }).waitFor();
  assert.match(page.url(), /\/workbench$/);
  const csv = 'participant_id,age,answer\nfixture-1,17,0\nfixture-2,22,"same, literal"\nfixture-3,31,\n';
  await page.getByLabel("Исходная база ответов").setInputFiles({ name: "fixture.csv", mimeType: "text/csv", buffer: Buffer.from(csv) });
  await page.getByText("Загружено записей: 3.", { exact: false }).waitFor();
  await page.getByLabel("ID участника", { exact: true }).selectOption("0");
  await page.getByRole("button", { name: /Отбор и классификация/ }).click();
  await page.getByLabel("Столбец критерия", { exact: true }).selectOption("1");
  await page.getByLabel("Значение", { exact: true }).fill("18");
  await page.getByLabel("Название группы", { exact: true }).fill("Adults");
  await page.getByRole("button", { name: "Добавить критерий", exact: true }).click();
  assert.equal(await page.getByText("После отбора", { exact: true }).locator("..").locator("strong").textContent(), "2");
  await page.getByRole("button", { name: /Карта формы/ }).click();
  await page.getByLabel("Ссылка Google Forms", { exact: true }).fill("https://docs.google.com/forms/d/e/fixture/viewform");
  await page.getByRole("button", { name: "Добавить вопрос", exact: true }).click();
  await page.getByLabel("Текст вопроса 1").fill("Exact question");
  await page.getByLabel("Столбец ответа 1").selectOption("2");
  await page.getByRole("button", { name: /Пакет для агента/ }).click();
  await page.getByLabel("Задача исследования", { exact: true }).fill("Disposable browser fixture transfer");
  assert.equal(await page.getByRole("button", { name: "Скачать пакет для агента" }).isDisabled(), true);
  await page.getByText(/отсутствуют 1 обязательных ответов/).waitFor();
  await page.getByRole("button", { name: /Отбор и классификация/ }).click();
  await page.getByLabel("Столбец критерия", { exact: true }).selectOption("2");
  await page.getByLabel("Условие", { exact: true }).selectOption("present");
  await page.getByLabel("Название группы", { exact: true }).fill("Complete answer");
  await page.getByRole("button", { name: "Добавить критерий", exact: true }).click();
  await page.getByRole("button", { name: /Пакет для агента/ }).click();
  const packetDownload = page.waitForEvent("download");
  await page.getByRole("button", { name: "Скачать пакет для агента" }).click();
  const packet = JSON.parse(await readFile(await (await packetDownload).path(), "utf8"));
  assert.equal(packet.source.sha256, createHash("sha256").update(csv).digest("hex"));
  assert.equal(packet.respondents.length, 1);
  assert.equal(packet.respondents[0].participant_ref, "fixture-2");
  assert.equal(packet.respondents[0].answers[0].value, "same, literal");
  assert.equal(packet.respondents[0].answers[0].source.row, 3);
  assert.equal(packet.execution.external_submission, false);
  const projectDownload = page.waitForEvent("download");
  await page.getByRole("button", { name: "Сохранить проект", exact: true }).click();
  const project = await readFile(await (await projectDownload).path());
  await page.getByRole("button", { name: "Очистить рабочую панель" }).click();
  await page.getByLabel("Файл сохранённого проекта").setInputFiles({ name: "respondent-project.json", mimeType: "application/json", buffer: project });
  await page.getByText("Проект восстановлен из файла.").waitFor();
  assert.equal(await page.getByLabel("ID участника", { exact: true }).inputValue(), "0");
  assert.equal(await page.getByText("После отбора", { exact: true }).locator("..").locator("strong").textContent(), "1");
  await page.getByLabel("Исходная база ответов").setInputFiles({ name: "modeled.json", mimeType: "application/json", buffer: Buffer.from(JSON.stringify({ data_origin: "modeled", records: [{ id: "fixture-model" }] })) });
  await page.getByRole("alert").filter({ hasText: /модельные профили/i }).waitFor();
  await page.getByRole("button", { name: /Психологический справочник/ }).click();
  await page.getByLabel("Поиск характеристики", { exact: true }).fill("Тревожность");
  await page.getByRole("button", { name: "Тревожность", exact: true }).first().click();
  assert.equal(await page.getByLabel("Название группы", { exact: true }).inputValue(), "Тревожность");
  await page.getByRole("button", { name: /База ответов/ }).click();
  if (process.env.BROWSER_SCREENSHOT_DIR) await page.screenshot({ path: `${process.env.BROWSER_SCREENSHOT_DIR}/workbench-desktop.png`, fullPage: true });
  await page.setViewportSize({ width: 390, height: 844 });
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth), true, "Mobile page must not overflow horizontally.");
  if (process.env.BROWSER_SCREENSHOT_DIR) await page.screenshot({ path: `${process.env.BROWSER_SCREENSHOT_DIR}/workbench-mobile.png`, fullPage: true });
  assert.deepEqual(errors, []);
  assert.deepEqual(posts, [], "Browser preparation must not transmit source records.");
  const research = await httpGet(server.baseUrl, "/participants");
  assert.ok([302, 303, 307, 308].includes(research.status));
  assert.equal((server.db.prepare("SELECT COUNT(*) AS count FROM participant").get()).count, 0);
  log("PASS: real browser import, filter, missing-answer gate, exact mapping/export/hash, project restore, origin rejection, dictionary, mobile layout; no POSTs or research writes.");
} finally { await browser?.close(); await server.stop(); removeTempDb(server.dbFile); }
